/* ============================================================================
   hub.js — the topic directory: every recorded video, with a badge saying
   whether an interactive version exists yet.

   Reads data/hub.json (generated by scripts/build-interactive.mjs) and renders
   one section per bab. Search + filters only toggle visibility afterwards —
   building 201 tiles once and filtering is cheaper than re-rendering on every
   keystroke (and it keeps focus in the search box).
   ========================================================================== */
(function () {
  'use strict';
  const { h } = IX;
  const root = document.getElementById('root');
  if (document.referrer && new URL(document.referrer).origin === location.origin) document.documentElement.classList.add('embedded');

  const q = new URLSearchParams(location.search);
  const state = { text: (q.get('q') || '').toLowerCase(), subject: q.get('mapel') || 'semua', ready: q.get('siap') === '1' };

  fetch('data/hub.json')
    .then((r) => r.json())
    .then(render)
    .catch(() => {
      root.textContent = '';
      root.append(
        h('div', { class: 'card q' }, [
          h('h2', { text: 'Daftar topik tidak terbaca' }),
          h('p', { class: 'muted', text: 'Halaman ini butuh server lokal: npm run dev (atau npm run preview), lalu buka /interaktif/. Jalankan node scripts/build-interactive.mjs untuk membuat data/hub.json.' }),
        ]),
      );
    });

  function render(hub) {
    root.textContent = '';
    const visible = []; // flat list of {it, el} kept for the filter pass

    root.append(
      h('header', { class: 'ix-top', style: { margin: '-60px -20px 0' } }, [
        h('div', { class: 'ix-top__brand' }, [
          h('div', { class: 'ix-top__mark', text: '✦' }),
          h('div', {}, [h('div', { text: 'Interaktif' }), h('div', { class: 'ix-top__sub', text: 'visual explainer OSN/KSN SD' })]),
        ]),
        h('div', { class: 'ix-top__spacer' }),
        h('a', { class: 'btn btn-sm', href: '../index.html', text: 'Buka aplikasi utama' }),
      ]),
    );

    root.append(
      h('section', { class: 'hero' }, [
        h('h1', { text: 'Tiap video, satu penjelasan hidup.' }),
        h('p', { text: 'Versi interaktif dari materi video: ilustrasi yang bergerak, titik info yang bisa diklik, kuis mini, lalu 100 soal lengkap dengan pembahasan tiap pilihan. Video aslinya tetap utuh — ini lapisan baru di sampingnya.' }),
        h('div', { class: 'stats' }, [
          stat(hub.total, 'video / topik'),
          stat(hub.withScenes, 'sudah interaktif'),
          stat(hub.babs.length, 'bab'),
          stat(hub.total * 100, 'soal'),
        ]),
      ]),
    );

    const search = h('input', { type: 'search', placeholder: 'Cari topik — mis. tuas, pecahan, listrik air…', value: state.text, 'aria-label': 'Cari topik' });
    const chips = h('div', { style: { display: 'flex', gap: '6px', flexWrap: 'wrap' } });
    root.append(h('div', { class: 'searchbar' }, [search, chips]));
    const list = h('div');
    const emptyMsg = h('div', { class: 'empty', text: 'Tidak ada topik yang cocok. Coba kata kunci lain.' });
    root.append(list, emptyMsg);

    for (const bab of hub.babs) {
      const sec = h('section', { class: 'bab fade-up' });
      const grid = h('div', { class: 'grid' });
      sec.append(
        h('div', { class: 'bab__head' }, [
          h('span', { class: 'bab__code', text: bab.code }),
          h('h2', { text: bab.title }),
          h('span', { class: `chip ${bab.subject === 'ipa' ? 'chip-ipa' : 'chip-mtk'}`, text: bab.subject.toUpperCase() }),
        ]),
        grid,
      );
      for (const it of bab.items) {
        const el = tile(it);
        grid.append(el);
        visible.push({ it, sec, el, bab });
      }
      list.append(sec);
    }

    function stat(n, label) {
      return h('div', { class: 'stat' }, [h('b', { text: String(n) }), h('span', { text: label })]);
    }

    function tile(it) {
      const badges = [
        h('span', { class: 'chip', text: `${it.questionCount} soal` }),
        it.isChapter ? h('span', { class: 'chip chip-accent', text: 'bab penuh' }) : null,
        it.hasScenes
          ? h('span', { class: 'chip', style: { borderColor: 'var(--ok)', color: 'var(--ok)', background: 'rgba(52,211,153,.12)' }, text: '✓ interaktif' })
          : h('span', { class: 'chip', text: 'segera' }),
      ];
      const inner = [
        h('span', { class: 'tile__n', text: it.n }),
        h('span', { class: 'tile__b' }, [h('b', { text: it.title }), h('span', {}, badges)]),
      ];
      if (!it.hasScenes) return h('div', { class: 'tile tile--soon', title: 'Ilustrasi untuk topik ini belum ditulis' }, inner);
      return h('a', { class: 'tile', href: `play.html?id=${encodeURIComponent(it.id)}`, title: it.fullTitle }, inner);
    }

    // ---- filters: pure visibility pass, no re-render -------------------------
    const subjectBtns = {};
    for (const s of ['semua', 'ipa', 'mtk']) {
      const b = h('button', { class: 'btn btn-sm', text: s === 'semua' ? 'Semua mapel' : s.toUpperCase() });
      b.onclick = () => { state.subject = s; paint(); };
      subjectBtns[s] = b;
      chips.append(b);
    }
    const readyBtn = h('button', { class: 'btn btn-sm', text: 'Hanya yang sudah interaktif' });
    readyBtn.onclick = () => { state.ready = !state.ready; paint(); };
    chips.append(readyBtn);

    search.oninput = () => { state.text = search.value.trim().toLowerCase(); paint(); };

    function paint() {
      for (const s in subjectBtns) {
        const on = state.subject === s;
        Object.assign(subjectBtns[s].style, on ? { background: 'var(--accent)', borderColor: 'var(--accent)', color: '#06101f' } : {});
      }
      Object.assign(readyBtn.style, state.ready ? { background: 'var(--accent)', borderColor: 'var(--accent)', color: '#06101f' } : {});
      let n = 0;
      for (const row of visible) {
        const { it, sec, el } = row;
        const ok =
          (state.subject === 'semua' || row.bab.subject === state.subject) &&
          (!state.ready || it.hasScenes) &&
          (!state.text || `${it.title} ${it.id} ${it.n} ${it.subBab || ''} ${it.slug}`.toLowerCase().includes(state.text));
        el.hidden = !ok;
        if (ok) n++;
        const others = [...sec.querySelectorAll('.tile')].some((x) => !x.hidden);
        sec.hidden = !others;
      }
      emptyMsg.hidden = n > 0;
      // ?q=…&auto=1 drops straight into the first interactive match
      if (q.get('auto') === '1' && state.text) {
        const first = visible.find((r) => !r.el.hidden && r.it.hasScenes);
        if (first) location.href = first.el.getAttribute('href');
      }
    }
    paint();
  }
})();